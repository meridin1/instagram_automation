@router.get("/api/instagram/accounts")
async def accounts(client_id: str = Depends(get_client_id)):
    """List the current client's Instagram accounts without encrypted tokens."""
    cursor = db().instagram_accounts.find(
        {"client_id": client_id},
        {"access_token": 0, "access_token_encrypted": 0},
    ).sort("updated_at", -1)

    results = []

    async for account in cursor:
        item = {key: value for key, value in account.items() if key != "_id"}
        item["id"] = str(account["_id"])
        results.append(item)

    return results


@router.post("/api/instagram/mappings")
async def create_mapping(
    payload: ProductMappingCreate,
    client_id: str = Depends(get_client_id),
):
    """Map an Instagram post/media ID to a product belonging to this client."""
    try:
        product_oid = ObjectId(payload.product_id)
    except Exception as exc:
        raise HTTPException(400, "Invalid product ID") from exc

    product = await db().products.find_one(
        {"_id": product_oid, "client_id": client_id}
    )

    if not product:
        raise HTTPException(404, "Product not found")

    result = await db().product_mappings.update_one(
        {
            "client_id": client_id,
            "instagram_media_id": payload.instagram_media_id,
        },
        {
            "$set": {
                "client_id": client_id,
                "instagram_media_id": payload.instagram_media_id,
                "instagram_post_id": payload.instagram_post_id,
                "product_id": payload.product_id,
                "updated_at": _utc_now(),
            },
            "$setOnInsert": {"created_at": _utc_now()},
        },
        upsert=True,
    )

    await db().products.update_one(
        {"_id": product_oid, "client_id": client_id},
        {
            "$set": {
                "instagram_post_id": payload.instagram_post_id,
                "instagram_media_id": payload.instagram_media_id,
                "updated_at": _utc_now(),
            }
        },
    )

    return {
        "ok": True,
        "mapping_id": str(result.upserted_id or payload.instagram_media_id),
    }


@router.get("/webhooks/instagram/{client_id}")
async def verify_webhook(client_id: str, request: Request):
    """Handle Meta's webhook verification challenge."""
    logger.info(
        "Instagram webhook verification request received: client_id=%s",
        client_id,
    )

    mode = request.query_params.get("hub.mode")
    verify_token = request.query_params.get("hub.verify_token")
    challenge = request.query_params.get("hub.challenge")

    if mode != "subscribe" or challenge is None:
        logger.warning(
            "Instagram webhook verification rejected: invalid mode/challenge"
        )
        raise HTTPException(400, "Invalid webhook verification request")

    config = await get_client_meta_config(client_id)
    expected_token = config.get("verify_token")

    if not expected_token or not hmac_compare_tokens(
        verify_token, expected_token
    ):
        logger.warning(
            "Instagram webhook verification rejected: token mismatch "
            "client_id=%s",
            client_id,
        )
        raise HTTPException(403, "Webhook verification token mismatch")

    logger.info(
        "Instagram webhook verification successful: client_id=%s",
        client_id,
    )

    return int(challenge)


def hmac_compare_tokens(received: str | None, expected: str) -> bool:
    """Constant-time comparison for webhook verification tokens."""
    import hmac

    if received is None:
        return False

    return hmac.compare_digest(received.encode(), expected.encode())


@router.post("/webhooks/instagram/{client_id}")
async def receive_webhook(client_id: str, request: Request):
    """
    Receive Meta Instagram webhook events.

    The first log line is deliberately before signature validation so Render
    shows that the request reached this route even when validation fails.
    """
    logger.info(
        "INSTAGRAM WEBHOOK RECEIVED: client_id=%s",
        client_id,
    )

    raw_body = await request.body()
    signature = request.headers.get("X-Hub-Signature-256")

    logger.info(
        "Instagram webhook request details: client_id=%s body_bytes=%s "
        "signature_present=%s",
        client_id,
        len(raw_body),
        bool(signature),
    )

    try:
        config = await get_client_meta_config(client_id)
    except Exception:
        logger.exception(
            "Could not load Instagram webhook configuration: client_id=%s",
            client_id,
        )
        raise HTTPException(500, "Could not load webhook configuration")

    service = InstagramService()

    # Verify against the app secrets configured for this integration.
    # Never log the secret, signature value, or full inbound message payload.
    valid_signature = (
        service.verify_signature(
            raw_body,
            signature,
            config.get("app_secret"),
        )
        or service.verify_signature(
            raw_body,
            signature,
            config.get("instagram_app_secret"),
        )
    )

    if not valid_signature:
        logger.warning(
            "Instagram webhook signature rejected: client_id=%s "
            "app_secret_configured=%s",
            client_id,
            bool(
                config.get("app_secret")
                or config.get("instagram_app_secret")
            ),
        )
        raise HTTPException(403, "Invalid Instagram webhook signature")

    try:
        payload = json.loads(raw_body.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        logger.warning(
            "Instagram webhook rejected: invalid JSON client_id=%s",
            client_id,
        )
        raise HTTPException(400, "Invalid webhook JSON")

    if not isinstance(payload, dict):
        raise HTTPException(400, "Webhook payload must be a JSON object")

    logger.info(
        "Instagram webhook payload received: client_id=%s object=%s "
        "entry_count=%s",
        client_id,
        payload.get("object"),
        len(payload.get("entry", []) or []),
    )

    events = _extract_message_events(payload)

    logger.info(
        "Instagram webhook message extraction completed: client_id=%s "
        "message_count=%s",
        client_id,
        len(events),
    )

    processed = 0
    skipped = 0
    errors = 0

    for event in events:
        # The recipient is the connected business account for an inbound DM.
        account = await db().instagram_accounts.find_one(
            {
                "instagram_user_id": event["recipient_id"],
                "client_id": client_id,
                "active": True,
            }
        )

        if not account:
            skipped += 1
            logger.warning(
                "Instagram webhook event has no matching active account: "
                "client_id=%s recipient_id=%s",
                client_id,
                event["recipient_id"],
            )
            continue

        logger.info(
            "Processing inbound Instagram message: client_id=%s "
            "account_record_id=%s sender_id=%s has_message_id=%s",
            client_id,
            str(account["_id"]),
            event["sender_id"],
            bool(event.get("message_id")),
        )

        try:
            result = await process_inbound(
                client_id=client_id,
                instagram_account_id=str(account["_id"]),
                sender_id=event["sender_id"],
                text=event["text"],
                send_to_instagram=True,
                external_message_id=event.get("message_id"),
                image_url=event.get("image_url"),
            )

            processed += 1

            logger.info(
                "Inbound Instagram message processed: client_id=%s "
                "account_record_id=%s result_status=%s",
                client_id,
                str(account["_id"]),
                result.get("status", "ok")
                if isinstance(result, dict)
                else "ok",
            )

        except Exception:
            errors += 1
            logger.exception(
                "Inbound Instagram processing failed: client_id=%s "
                "account_record_id=%s",
                client_id,
                str(account["_id"]),
            )

    logger.info(
        "Instagram webhook finished: client_id=%s extracted=%s "
        "processed=%s skipped=%s errors=%s",
        client_id,
        len(events),
        processed,
        skipped,
        errors,
    )

    # Acknowledge successfully received webhook payloads so Meta does not
    # repeatedly retry events because of an internal processing exception.
    return {
        "ok": True,
        "received": len(events),
        "processed": processed,
        "skipped": skipped,
        "errors": errors,
    }


