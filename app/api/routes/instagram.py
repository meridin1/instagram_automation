def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _extract_message_events(payload: dict[str, Any]) -> list[dict[str, Any]]:
    """
    Extract supported Instagram messaging events from Meta's webhook payload.

    Supports text messages and attachment-only messages, so a customer
    can send a product photo or voice message without typing a greeting.
    """
    events: list[dict[str, Any]] = []

    for entry in payload.get("entry", []) or []:
        if not isinstance(entry, dict):
            continue

        for messaging in entry.get("messaging", []) or []:
            if not isinstance(messaging, dict):
                continue

            # Ignore echo messages generated by the connected account itself.
            if messaging.get("message", {}).get("is_echo"):
                continue

            message = messaging.get("message") or {}
            sender_id = (messaging.get("sender") or {}).get("id")
            recipient_id = (messaging.get("recipient") or {}).get("id")

            if not sender_id or not recipient_id:
                logger.warning(
                    "Instagram messaging event missing sender/recipient IDs"
                )
                continue

            text = message.get("text")
            attachments = message.get("attachments") or []
            image_url = None
            attachment_type = None
            for attachment in attachments:
                if not isinstance(attachment, dict):
                    continue
                kind = str(attachment.get("type", "attachment")).lower()
                if kind == "image" and not image_url:
                    attachment_type = "image"
                    image_url = (attachment.get("payload") or {}).get("url")
                elif attachment_type is None:
                    attachment_type = kind

            # Represent media as an internal marker. The conversation service
            # can decide how to process the marker.
            if not text and attachments:
                attachment_types = {
                    str(item.get("type", "attachment")).lower()
                    for item in attachments
                    if isinstance(item, dict)
                }

                if "image" in attachment_types:
                    text = "[instagram_attachment:image]"
                elif "audio" in attachment_types:
                    text = "[instagram_attachment:audio]"
                elif "video" in attachment_types:
                    text = "[instagram_attachment:video]"
                else:
                    text = "[instagram_attachment:other]"

            # Ignore events that do not contain a supported message.
            if not text:
                logger.info(
                    "Instagram event skipped: no supported text or attachment"
                )
                continue

            events.append(
                {
                    "sender_id": str(sender_id),
                    "recipient_id": str(recipient_id),
                    "text": text,
                    "message_id": message.get("mid"),
                    "timestamp": messaging.get("timestamp"),
                    "image_url": image_url,
                    "attachment_type": attachment_type,
                    "has_image": bool(image_url),
                }
            )

    return events


@router.post("/api/instagram/accounts")
async def create_account(
    payload: InstagramAccountCreate,
    client_id: str = Depends(get_client_id),
):
    """Save a customer's Instagram account and encrypt its access token."""
    instagram_user_id = payload.instagram_user_id.strip()
    username = payload.username.strip().lstrip("@")
    token = (payload.access_token or "").strip()

    existing = await db().instagram_accounts.find_one(
        {
            "client_id": client_id,
            "instagram_user_id": instagram_user_id,
        }
    )

    owner = await db().instagram_accounts.find_one(
        {"instagram_user_id": instagram_user_id}
    )

    if owner and owner.get("client_id") != client_id:
        raise HTTPException(
            status_code=409,
            detail=(
                "This Instagram account is already connected "
                "to another Meridin workspace."
            ),
        )

    if not token and not existing:
        raise HTTPException(
            status_code=422,
            detail="Instagram access token is required for the first connection.",
        )

    values: dict[str, Any] = {
        "client_id": client_id,
        "instagram_user_id": instagram_user_id,
        "username": username,
        "active": True,
        "updated_at": _utc_now(),
    }

    if token:
        values["access_token_encrypted"] = encrypt_secret(token)

    if payload.token_expires_at:
        values["token_expires_at"] = payload.token_expires_at

    await db().instagram_accounts.update_one(
        {
            "client_id": client_id,
            "instagram_user_id": instagram_user_id,
        },
        {
            "$set": values,
            "$setOnInsert": {"created_at": _utc_now()},
        },
        upsert=True,
    )

    logger.info(
        "Instagram account saved: client_id=%s account_id=%s",
        client_id,
        instagram_user_id,
    )

    return {
        "ok": True,
        "username": username,
        "instagram_user_id": instagram_user_id,
        "token_saved": True,
    }


@router.post("/api/instagram/accounts/{account_id}/subscribe")
async def subscribe_account(
    account_id: str,
    client_id: str = Depends(get_client_id),
):
    """Subscribe the connected Instagram account to messaging webhooks."""
    try:
        account_oid = ObjectId(account_id)
    except Exception as exc:
        raise HTTPException(400, "Invalid Instagram account record ID") from exc

    account = await db().instagram_accounts.find_one(
        {
            "_id": account_oid,
            "client_id": client_id,
            "active": True,
        }
    )

    if not account:
        raise HTTPException(404, "Active Instagram account not found")

    config = await get_client_meta_config(client_id)
    access_token = account_access_token(account)

    logger.info(
        "Starting Instagram webhook subscription: client_id=%s account_id=%s",
        client_id,
        account.get("instagram_user_id"),
    )

    result = await InstagramService().subscribe_messages(
        account["instagram_user_id"],
        access_token,
        config,
    )

    await db().instagram_accounts.update_one(
        {"_id": account_oid, "client_id": client_id},
        {
            "$set": {
                "webhook_subscribed": True,
                "webhook_subscribed_at": _utc_now(),
            }
        },
    )

    logger.info(
        "Instagram subscription request completed: client_id=%s account_id=%s",
        client_id,
        account.get("instagram_user_id"),
    )

    return {"ok": True, "result": result}


